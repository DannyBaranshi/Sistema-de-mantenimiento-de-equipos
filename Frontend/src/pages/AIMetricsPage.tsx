import { BarChart3, CheckCircle, TrendingUp, XCircle } from "lucide-react";
import { useAIMetrics, useRecentFeedbacks } from "../hooks/useFeedback";

export default function AIMetricsPage() {
  const { data: metrics, isLoading } = useAIMetrics();
  const { data: recent } = useRecentFeedbacks(10);

  if (isLoading) return <p className="p-8 text-gray-400">Cargando métricas...</p>;
  if (!metrics) return <p className="p-8 text-red-500">No se pudieron cargar las métricas.</p>;

  return (
    <div className="space-y-6 p-8">
      <div>
        <h1 className="text-2xl font-semibold text-white flex items-center gap-2">
          <BarChart3 size={24} /> Métricas de la IA
        </h1>
        <p className="text-sm text-gray-400">
          Precisión del diagnóstico asistido y aprendizaje continuo.
        </p>
      </div>

      <div className="grid grid-cols-1 gap-4 md:grid-cols-2 lg:grid-cols-4">
        <div className="rounded-xl border border-blue-500/30 bg-blue-500/5 p-5">
          <p className="text-sm font-medium text-gray-400">Diagnósticos totales</p>
          <p className="mt-2 text-3xl font-semibold text-white">{metrics.totalDiagnoses}</p>
        </div>
        <div className="rounded-xl border border-green-500/30 bg-green-500/5 p-5">
          <p className="text-sm font-medium text-gray-400 flex items-center gap-2">
            <CheckCircle size={14} /> Aciertos
          </p>
          <p className="mt-2 text-3xl font-semibold text-white">{metrics.correctPredictions}</p>
        </div>
        <div className="rounded-xl border border-red-500/30 bg-red-500/5 p-5">
          <p className="text-sm font-medium text-gray-400 flex items-center gap-2">
            <XCircle size={14} /> Correcciones
          </p>
          <p className="mt-2 text-3xl font-semibold text-white">{metrics.incorrectPredictions}</p>
        </div>
        <div className="rounded-xl border border-yellow-500/30 bg-yellow-500/5 p-5">
          <p className="text-sm font-medium text-gray-400 flex items-center gap-2">
            <TrendingUp size={14} /> Precisión
          </p>
          <p className="mt-2 text-3xl font-semibold text-white">
            {Math.round(metrics.accuracy * 100)}%
          </p>
        </div>
      </div>

      <div className="rounded-xl border border-white/10 bg-[#0f1729] p-6">
        <h2 className="text-lg font-semibold text-white mb-2">Aprendizaje continuo</h2>
        <p className="text-sm text-gray-400">
          Entradas de la biblioteca generadas automáticamente por feedback:
        </p>
        <p className="mt-2 text-3xl font-semibold text-blue-400">
          {metrics.autoGeneratedKnowledgeEntries}
        </p>
      </div>

      <div className="rounded-xl border border-white/10 bg-[#0f1729] p-6">
        <h2 className="text-lg font-semibold text-white mb-4">Feedback reciente</h2>
        {recent && recent.length > 0 ? (
          <div className="space-y-2">
            {recent.map((f) => (
              <div
                key={f.id}
                className={`rounded-lg border p-3 ${
                  f.isCorrect
                    ? "border-green-500/20 bg-green-500/5"
                    : "border-red-500/20 bg-red-500/5"
                }`}
              >
                <div className="flex items-center justify-between">
                  <p className="text-sm font-medium text-white">
                    {f.technicianName}
                  </p>
                  <span className={`text-xs font-medium ${f.isCorrect ? "text-green-400" : "text-red-400"}`}>
                    {f.isCorrect ? "✓ Acertó" : "✗ Corregido"}
                  </span>
                </div>
                <p className="text-xs text-gray-400 mt-1">
                  Predicho: <span className="text-gray-300">{f.predictedCause}</span>
                </p>
                <p className="text-xs text-gray-400">
                  Real: <span className="text-gray-300">{f.actualCause}</span>
                </p>
                {f.notes && (
                  <p className="text-xs text-gray-500 mt-1 italic">{f.notes}</p>
                )}
              </div>
            ))}
          </div>
        ) : (
          <p className="text-sm text-gray-500">Aún no hay feedback registrado.</p>
        )}
      </div>
    </div>
  );
}
